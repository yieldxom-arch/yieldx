// YieldX AI Integration — Anthropic Claude
//
// All Claude calls go through the `ai-proxy` Supabase Edge Function, so the
// Anthropic API key stays server-side and never reaches the browser bundle.
// Personal details (names of people, contact and ID fields) are stripped from
// study data before it is sent to the model.
