import { supabase } from '@/lib/supabase';

export interface AiFeedback {
  score: number;           // 0-100
  strengths: string[];     // 3 specific strengths
  risks: string[];         // 3 specific risks / weaknesses
  suggestions: string[];   // 2 concrete improvements
  financialProjection?: FinancialProjectionRow[]; // Level 6 only
}

export interface FinancialProjectionRow {
  year: string;
  revenue: string;
  expenses: string;
  netProfit: string;
  cumulativeCashFlow: string;
}

const LEVEL_NAMES: Record<number, { ar: string; en: string }> = {
  0: { ar: 'اختيار نوع المشروع', en: 'Project Type Selection' },
  1: { ar: 'تحليل السوق', en: 'Market Analysis' },
  2: { ar: 'المتطلبات القانونية والتراخيص', en: 'Legal Requirements & Licenses' },
  3: { ar: 'المتطلبات التشغيلية', en: 'Operational Requirements' },
  4: { ar: 'إدارة الأصول', en: 'Asset Management' },
  5: { ar: 'تخطيط الموظفين', en: 'Staff Planning' },
  6: { ar: 'التخطيط المالي', en: 'Financial Planning' },
  7: { ar: 'معلومات المساهمين وهيكل الملكية', en: 'Shareholder Information & Ownership Structure' },
};

// ─── Privacy: strip personal identifiers before anything leaves the browser ───

const PERSONAL_KEYS = /^(email|e-?mail|phone|phoneNumber|mobile|whatsapp|civilId|civilNumber|nationalId|passport|passportNumber|idNumber|address|homeAddress|dateOfBirth|dob|birthDate)$/i;
const PERSON_CONTAINERS = /(share|partner|owner|founder|employee|staff|member|person|people|director|manager|contact)/i;
const PERSON_NAME_KEYS = /^(name|fullName|firstName|lastName|ownerName|founderName|partnerName|shareholderName|employeeName)$/i;

export function redactPersonalData(value: any, parentKey = ''): any {
  if (Array.isArray(value)) return value.map((v) => redactPersonalData(v, parentKey));
  if (value && typeof value === 'object') {
    const out: Record<string, any> = {};
    for (const [k, v] of Object.entries(value)) {
      if (PERSONAL_KEYS.test(k)) continue; // drop contact / ID fields entirely
      if (PERSON_NAME_KEYS.test(k) && (PERSON_CONTAINERS.test(parentKey) || /(owner|founder|partner|shareholder|employee)/i.test(k))) {
        out[k] = '[person]';
        continue;
      }
      // Large base64 blobs (images, documents) are never useful to the model.
      if (typeof v === 'string' && v.length > 2000 && /^data:/.test(v)) continue;
      out[k] = redactPersonalData(v, k);
    }
    return out;
  }
  return value;
}

export async function callClaude(
  prompt: string,
  systemPrompt: string,
  maxTokens = 1024,
): Promise<string> {
  const supabaseUrl = (import.meta as any).env?.VITE_SUPABASE_URL;
  if (!supabaseUrl) throw new Error('Missing VITE_SUPABASE_URL');

  const { data } = await supabase.auth.getSession();
  const token = data.session?.access_token;
  if (!token) throw new Error('Not authenticated');

  const response = await fetch(`${supabaseUrl}/functions/v1/ai-proxy`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ prompt, system: systemPrompt, maxTokens }),
  });

  if (!response.ok) {
    const err = await response.json().catch(() => ({ error: response.statusText }));
    throw new Error(`AI service error ${response.status}: ${err.error ?? ''}`);
  }

  const json = await response.json();
  return String(json.text ?? '').trim();
}

// ─── Level 6: projection table is CALCULATED, never generated by the model ───

function buildCalculatedProjection(
  formData: Record<string, any>,
  language: 'ar' | 'en',
): FinancialProjectionRow[] | undefined {
  const rows: any[] = Array.isArray(formData?.projections) ? formData.projections : [];
  if (rows.length === 0) return undefined;
  const fmt = (n: number) => Math.round(n).toLocaleString('en-US');
  let cumulative = -(Number(formData.totalInvestment) || 0);
  return rows.slice(0, 3).map((p, i) => {
    const revenue = Number(p.revenue) || 0;
    const expenses = (Number(p.costs) || 0) + (Number(p.depreciation) || 0) + (Number(p.interest) || 0);
    const netProfit = Number(p.profit) || 0;
    cumulative += netProfit + (Number(p.depreciation) || 0); // depreciation is non-cash
    return {
      year: language === 'ar' ? `السنة ${i + 1}` : `Year ${i + 1}`,
      revenue: fmt(revenue),
      expenses: fmt(expenses),
      netProfit: fmt(netProfit),
      cumulativeCashFlow: fmt(cumulative),
    };
  });
}

